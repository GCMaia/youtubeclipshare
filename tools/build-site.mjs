// Prepares web/ (the YouClip web player at youclip.ca, a static site) from the extension's own
// sources: the shared clip code, the translations it needs, and the icons.
// Run it after changing src/clip-utils.js, _locales/ or icons/:
//   node tools/build-site.mjs           write the files
//   node tools/build-site.mjs --check   only check web/ is up to date (used by the tests)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const WEB = join(ROOT, 'web');
const SITE_KEYS = ['lang', 'badgeLabel', 'clipLength', 'clipEnded', 'replayClip', 'keepWatching', 'watchOnYouTube', 'siteInvalidLink', 'siteCantEmbed'];
const HEADER = '// Generated by tools/build-site.mjs from the extension sources. Do not edit.\n';

function siteStrings() {
  const out = {};
  for (const locale of readdirSync(join(ROOT, '_locales')).sort()) {
    const messages = JSON.parse(readFileSync(join(ROOT, '_locales', locale, 'messages.json'), 'utf8'));
    out[locale] = {};
    for (const key of SITE_KEYS) {
      const entry = messages[key];
      if (!entry) throw new Error(`_locales/${locale} is missing "${key}"`);
      // $NAME$ placeholders become $1, $2… the way chrome.i18n substitutes them.
      out[locale][key] = entry.message.replace(/\$(\w+)\$/g, (m, name) => entry.placeholders?.[name.toLowerCase()]?.content ?? m);
    }
  }
  return `${HEADER}window.YOUCLIP_STRINGS = ${JSON.stringify(out, null, 2)};\n`;
}

const files = {
  'clip-utils.js': HEADER + readFileSync(join(ROOT, 'src/clip-utils.js'), 'utf8'),
  'strings.js': siteStrings(),
  'icon48.png': readFileSync(join(ROOT, 'icons/icon48.png')),
  'icon128.png': readFileSync(join(ROOT, 'icons/icon128.png')),
};

const normalize = (data) => (typeof data === 'string' ? Buffer.from(data.replace(/\r\n/g, '\n')) : data);
const isCurrent = (name, data) => {
  const path = join(WEB, name);
  if (!existsSync(path)) return false;
  const onDisk = readFileSync(path);
  return typeof data === 'string' ? normalize(onDisk.toString('utf8')).equals(normalize(data)) : onDisk.equals(data);
};

const stale = Object.entries(files).filter(([name, data]) => !isCurrent(name, data));

if (process.argv.includes('--check')) {
  if (stale.length) {
    console.error(`web/ is out of date: ${stale.map(([n]) => n).join(', ')}. Run: node tools/build-site.mjs`);
    process.exit(1);
  }
  console.log('web/ is up to date');
} else {
  for (const [name, data] of stale) writeFileSync(join(WEB, name), data);
  console.log(stale.length ? `updated web/: ${stale.map(([n]) => n).join(', ')}` : 'web/ was already up to date');
}
